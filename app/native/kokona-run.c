/*
 * kokona-run -- zero-shell launcher for the bundled kokona-glibc prefix.
 *
 * WHY THIS IS A NATIVE BINARY
 * ---------------------------
 * The old kokona-grun was a ~170 line /system/bin/sh script. On Android that
 * shell is toybox sh: one startup plus a fork+exec for every `dirname`, `tr`,
 * `getprop`, `cd`/`pwd` and command substitution. Device measurements put the
 * wrapper at 175-192 ms per call while the same program exec'd straight
 * through the loader took 6 ms -- the glibc side was never the bottleneck.
 *
 * This launcher does the same preparation in-process and finishes with ONE
 * execve() of the loader. No shell, no forks, no external commands, no
 * environment leakage into bionic processes.
 *
 * The same argv[0] dispatches the prefixed glibc tools (kiconv, kgetent,
 * kldd, ...), so there is exactly one implementation instead of seven copied
 * shell scripts.
 *
 * Build (Android):
 *   aarch64-linux-android24-clang -O2 -Wall -Wextra \
 *     -DKOKONA_PREFIX='"/data/user/0/.../kokona-glibc"' \
 *     -o kokona-run kokona-run.c
 * Build (host, for logic tests):
 *   gcc -O2 -Wall -Wextra -DKOKONA_PREFIX='"/tmp/prefix"' -o kokona-run kokona-run.c
 *
 * KOKONA_GLIBC overrides the compiled prefix. KOKONA_DRY_RUN=1 prints what
 * would be exec'd instead of exec'ing it (host-side verification only).
 */
#define _POSIX_C_SOURCE 200809L
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <sys/types.h>
#include <sys/wait.h>
#include <unistd.h>

#ifndef KOKONA_PREFIX
#define KOKONA_PREFIX "/data/user/0/com.kokonaharness.android.akizuki/files/KokonaRuntime/kokona-glibc"
#endif

#define PATHBUF 4096
#define NS_MAX 16

/* The prefix is a build-time constant (~100 chars); 1024 leaves every derived
 * path far below PATHBUF so no snprintf can ever truncate. */
static char G[1024];
static char LOADER[PATHBUF];
static char LP[PATHBUF];

static const char *base_name(const char *p) {
    const char *slash = strrchr(p, '/');
    return slash ? slash + 1 : p;
}

static int dir_exists(const char *p) {
    struct stat st;
    return stat(p, &st) == 0 && S_ISDIR(st.st_mode);
}

static int file_exists(const char *p) {
    struct stat st;
    return stat(p, &st) == 0 && S_ISREG(st.st_mode);
}

/* ---------------------------------------------------------------- DNS ---- */

/* Accept dotted-quad IPv4 with every octet in 0..255. */
static int is_ipv4(const char *s) {
    int parts = 0;
    while (*s) {
        int value = 0, digits = 0;
        while (*s >= '0' && *s <= '9') {
            value = value * 10 + (*s - '0');
            if (++digits > 3 || value > 255) return 0;
            s++;
        }
        if (!digits) return 0;
        parts++;
        if (*s == '.') { s++; continue; }
        if (*s) return 0;
        break;
    }
    return parts == 4;
}

/* Accept IPv6 with at least two colons and only hex/colon/dot characters. */
static int is_ipv6(const char *s) {
    size_t n = strlen(s);
    int colons = 0;
    if (n < 3 || n > 45) return 0;
    for (size_t i = 0; i < n; i++) {
        char c = s[i];
        if (c == ':') { colons++; continue; }
        if ((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') ||
            (c >= 'A' && c <= 'F') || c == '.') continue;
        return 0;
    }
    return colons >= 2;
}

/*
 * Regenerate etc/resolv.conf from etc/dns.servers, but only when the result
 * actually differs -- otherwise the file's mtime must not move. Android 10+
 * no longer publishes net.dns*, so the app writes the live list to
 * etc/dns.servers on every network change. Junk lines, comments, half-written
 * rows and trailing junk are dropped; a totally unusable file falls back to
 * public resolvers. No getprop, no external command, no pipe.
 */
static void prepare_dns(void) {
    char want[4096];
    size_t used = (size_t)snprintf(want, sizeof want, "# generated by kokona-run\n");
    int count = 0;

    char src[PATHBUF];
    snprintf(src, sizeof src, "%s/etc/dns.servers", G);
    FILE *in = fopen(src, "r");
    if (in) {
        char line[512];
        while (fgets(line, sizeof line, in)) {
            size_t n = strlen(line);
            while (n && (line[n - 1] == '\n' || line[n - 1] == '\r')) line[--n] = '\0';
            if (strncmp(line, "nameserver ", 11) != 0) continue;
            const char *ip = line + 11;
            if (*ip == '\0' || strchr(ip, ' ') || strchr(ip, '\t')) continue;
            if (!is_ipv4(ip) && !is_ipv6(ip)) continue;
            if (count >= NS_MAX) break;
            int added = snprintf(want + used, sizeof want - used, "nameserver %s\n", ip);
            if (added < 0 || (size_t)added >= sizeof want - used) break;
            used += (size_t)added;
            count++;
        }
        fclose(in);
    }
    if (count == 0) {
        used += (size_t)snprintf(want + used, sizeof want - used,
                                 "nameserver 1.1.1.1\nnameserver 8.8.8.8\n");
    }

    char dst[PATHBUF];
    snprintf(dst, sizeof dst, "%s/etc/resolv.conf", G);
    char current[sizeof want] = "";
    size_t got = 0;
    FILE *cur = fopen(dst, "r");
    if (cur) {
        got = fread(current, 1, sizeof current - 1, cur);
        current[got] = '\0';
        fclose(cur);
    }
    if (got == used && memcmp(current, want, used) == 0) return;  /* unchanged */

    FILE *out = fopen(dst, "w");
    if (!out) return;  /* read-only prefix: keep running with the old file */
    fwrite(want, 1, used, out);
    fclose(out);
}

/* ------------------------------------------------------------- locale ---- */

/*
 * This prefix ships no compiled locale data. C is built into libc, never
 * warns and is byte-transparent, so LANG *and* LC_ALL both have to be pinned
 * to C: leaving LANG=en_US.UTF-8 behind made `locale` print three
 * "Cannot set LC_* to default locale" lines on every invocation. Once locale
 * data is present, an explicit caller choice is honoured again.
 */
static void prepare_locale(void) {
    char archive[PATHBUF], dir[PATHBUF];
    snprintf(archive, sizeof archive, "%s/lib/locale/locale-archive", G);
    snprintf(dir, sizeof dir, "%s/lib/locale", G);
    if (file_exists(archive)) return;
    (void)dir;
    setenv("LANG", "C", 1);
    setenv("LC_ALL", "C", 1);
}

/* -------------------------------------------------------------- setup ---- */

static void prepare_env(void) {
    /* Never leak glibc libraries into a bionic process. This is the exact
     * failure mode that produced `bad ELF magic` in the old kldd wrapper. */
    unsetenv("LD_PRELOAD");
    unsetenv("LD_LIBRARY_PATH");
    unsetenv("LD_DEBUG");
    unsetenv("LD_DEBUG_OUTPUT");
    unsetenv("LD_BIND_NOW");

    char rt[1024];
    snprintf(rt, sizeof rt, "%s", G);
    char *slash = strrchr(rt, '/');
    if (slash) *slash = '\0';
    char cert[PATHBUF];
    snprintf(cert, sizeof cert, "%s/etc/tls/cert.pem", rt);
    if (file_exists(cert)) setenv("SSL_CERT_FILE", cert, 1);

    const char *home = getenv("HOME");
    char extra[1024];
    if (home && *home) {
        snprintf(extra, sizeof extra, "%s/.local/lib/kokona-glibc", home);
    } else {
        extra[0] = '\0';
    }
    if (extra[0] && dir_exists(extra)) {
        snprintf(LP, sizeof LP, "%s/lib:%s", G, extra);
    } else {
        snprintf(LP, sizeof LP, "%s/lib", G);
    }
}

/* ------------------------------------------------------------ dispatch ---- */

struct alias { const char *name; const char *tool; int list_mode; };

static const struct alias ALIASES[] = {
    {"kiconv",   "iconv",   0},
    {"kgetent",  "getent",  0},
    {"kgetconf", "getconf", 0},
    {"klocale",  "locale",  0},
    {"kgencat",  "gencat",  0},
    {"kpldd",    "pldd",    0},
    {"kldd",     NULL,      1},  /* loader --list, never exec the ldd script */
    {NULL,       NULL,      0},
};

static const struct alias *find_alias(const char *name) {
    for (const struct alias *a = ALIASES; a->name; a++) {
        if (strcmp(a->name, name) == 0) return a;
    }
    return NULL;
}

/*
 * Build the loader argv:
 *   loader --library-path LP [--list] <program> [args...]
 * Returns a malloc'd NULL-terminated array; the caller never comes back on
 * success because execv() replaces this process.
 */
/*
 * Build the loader argv from an already-trimmed argument list:
 *   loader --library-path LP [--list] <program> [args...]
 * `args` has `n` entries and is NULL-terminated by the caller's array.
 */
static char **build_argv(const struct alias *alias, int n, char **args) {
    int extra = alias ? 1 : 0;
    char **out = calloc((size_t)n + extra + 5, sizeof(char *));
    if (!out) return NULL;
    int i = 0;
    out[i++] = LOADER;
    out[i++] = (char *)"--library-path";
    out[i++] = LP;
    if (alias && alias->list_mode) out[i++] = (char *)"--list";
    if (alias && alias->tool) {
        char *tool = malloc(PATHBUF);
        if (!tool) { free(out); return NULL; }
        snprintf(tool, PATHBUF, "%s/bin/%s", G, alias->tool);
        out[i++] = tool;
    }
    for (int j = 0; j < n; j++) out[i++] = args[j];
    out[i] = NULL;
    return out;
}

static void show_help(void) {
    puts("kokona-run - run a glibc-linked arm64 program on the bundled glibc prefix");
    puts("");
    puts("usage: kokona-run [--] <program> [args...]");
    puts("       kokona-run --exec [--] <program> [args...]   skip environment prep");
    puts("       kokona-run --shell                            read commands from stdin");
    puts("       kokona-run --version | --help");
    puts("");
    puts("<program> must be a path (./x or /abs/x); the loader does not search PATH.");
    puts("glibc tools: kiconv kgetent kgetconf klocale kldd kgencat kpldd");
    printf("prefix: %s\n", G);
}

/* One interactive process: pay the preparation cost once, then only the
 * loader cost per command. Stdin lines are whitespace-split (no quoting). */
static int shell_loop(void) {
    char line[2048];
    while (fgets(line, sizeof line, stdin)) {
        char *tokens[64];
        int n = 0;
        for (char *p = strtok(line, " \t\r\n"); p && n < 60;
             p = strtok(NULL, " \t\r\n")) {
            tokens[n++] = p;
        }
        if (n == 0) continue;
        char **nav = build_argv(NULL, n, tokens);
        if (!nav) return 127;
        pid_t pid = fork();
        if (pid == 0) {
            execv(LOADER, nav);
            _exit(127);
        }
        if (pid > 0) {
            int status = 0;
            waitpid(pid, &status, 0);
        }
        free(nav);
    }
    return 0;
}

int main(int argc, char **argv) {
    const char *name = base_name(argv[0] ? argv[0] : "kokona-grun");
    const char *override = getenv("KOKONA_GLIBC");
    snprintf(G, sizeof G, "%s", (override && *override) ? override : KOKONA_PREFIX);
    snprintf(LOADER, sizeof LOADER, "%s/lib/ld-linux-aarch64.so.1", G);

    if (access(LOADER, X_OK) != 0) {
        fprintf(stderr, "kokona-run: glibc runtime missing at %s\n", G);
        return 127;
    }

    const struct alias *alias = find_alias(name);

    /* Friendly entry points, before any preparation. */
    if (argc > 1 && (strcmp(argv[1], "-h") == 0 || strcmp(argv[1], "--help") == 0)) {
        show_help();
        return 0;
    }
    if (argc > 1 && (strcmp(argv[1], "-V") == 0 || strcmp(argv[1], "--version") == 0)) {
        printf("kokona-run (KokonaRuntime) glibc prefix %s\n", G);
        return 0;
    }

    /* Trim options by advancing a view into argv instead of memmove()ing it:
     * the original argv array stays NULL-terminated exactly as the C runtime
     * built it, so there is no off-by-one to lose the terminator. */
    char **args = argv + 1;
    int n = argc - 1;
    int fast = 0, shell = 0;
    if (!alias && n > 0 && strcmp(args[0], "--exec") == 0) { fast = 1; args++; n--; }
    if (!alias && n > 0 && strcmp(args[0], "--shell") == 0) { shell = 1; args++; n--; }
    if (n > 0 && strcmp(args[0], "--") == 0) { args++; n--; }

    if (!fast) {
        prepare_dns();
        prepare_locale();
    }
    prepare_env();

    const char *dry = getenv("KOKONA_DRY_RUN");
    if (dry && strcmp(dry, "1") == 0) {
        char **nav = build_argv(alias, n, args);
        printf("LANG=%s LC_ALL=%s\n", getenv("LANG") ? getenv("LANG") : "",
               getenv("LC_ALL") ? getenv("LC_ALL") : "");
        printf("LD_LIBRARY_PATH=%s\n", getenv("LD_LIBRARY_PATH") ? getenv("LD_LIBRARY_PATH") : "<unset>");
        printf("LP=%s\n", LP);
        if (nav) {
            for (int i = 0; nav[i]; i++) printf("argv[%d]=%s\n", i, nav[i]);
            free(nav);
        }
        return 0;
    }

    if (shell) return shell_loop();

    if (!alias && n < 1) {
        fprintf(stderr, "kokona-run: missing program path (try --help)\n");
        return 127;
    }

    char **nav = build_argv(alias, n, args);
    if (!nav) return 127;
    execv(LOADER, nav);
    fprintf(stderr, "kokona-run: cannot exec %s: %s\n", LOADER, strerror(errno));
    free(nav);
    return 127;
}
